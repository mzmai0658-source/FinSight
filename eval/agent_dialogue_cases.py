def cases(split):
    groups = DEVELOPMENT if split == 'dialogue_development' else HOLDOUT
    prefix = 'semantic-dev' if split == 'dialogue_development' else 'semantic-held'
    result = []
    for g, turns in enumerate(groups, 1):
        for t, (question, action) in enumerate(turns, 1):
            result.append({'id':f'{prefix}-{g:02d}-{t}', 'group':f'{prefix}-{g:02d}',
                           'category':'semantic_dialogue', 'question':question,
                           'expected_action':action})
    assert len(result) == (60 if split == 'dialogue_development' else 30)
    return result
