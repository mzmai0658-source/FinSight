def cases(split='development'):
    if split == 'holdout':
        return [dict(id=f'h{i+1:02}', group=f'h{i+1:02}', category='holdout', question=q) for i,q in enumerate(HOLDOUT)]
    if split == 'holdout_fresh':
        return [dict(id=f'j{i+1:02}', group='j-dialog' if i>=26 else f'j{i+1:02}',
                     category='holdout_fresh', question=q) for i,q in enumerate(HOLDOUT_FRESH)]
    if split == 'holdout_final':
        return [dict(id=f'k{i+1:02}', group='k-dialog' if i>=27 else f'k{i+1:02}',
                     category='holdout_final', question=q) for i,q in enumerate(HOLDOUT_FINAL)]
    result=[]
    for family, entries in FAMILIES.items():
        for i, entry in enumerate(entries):
            question, codes, years, fields, *period = entry
            identity=f'{family}-{i+1}'
            result.append(dict(id=identity, group=identity, category=family, question=question,
                               expected=dict(codes=codes.split(',') if codes else [], years=years, fields=fields,
                                             period=period[0] if period else 'FY')))
    for i, conversation in enumerate(CONVERSATIONS):
        result.extend(dict(id=f'dialog-{i+1}-{j+1}', group=f'dialog-{i+1}', category='dialog', question=q)
                      for j,q in enumerate(conversation))
    assert len(result)==120
    return result
